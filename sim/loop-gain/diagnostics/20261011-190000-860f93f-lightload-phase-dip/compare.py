#!/usr/bin/env python3
"""Issue #365: build tables.md from the saved run results (stdlib only, read-only on runs/)."""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("lightload_extract", HERE / "lightload_extract.py")
ll = importlib.util.module_from_spec(spec)
sys.modules["lightload_extract"] = ll
spec.loader.exec_module(ll)


def load(run):
    return json.loads((HERE / "runs" / run / "result.json").read_text())


def f(x, n=1):
    return "-" if x is None else f"{x:.{n}f}"


def main():
    base, tail, rcz = load("base_tt"), load("tail2_tt"), load("rcz16_tt")
    out = ["# Tables (generated by compare.py from runs/*/result.json; tt / 27 C / 3.30 V only)\n"]
    out.append("## Margins (PM deg / worst GM dB / crossover Hz / status), all legs valid unless marked\n")
    out.append("| leg | baseline | tail x2 | R_CZ x16 |")
    out.append("|---|---|---|---|")
    for i, p in enumerate(base["points"]):
        row = [p["label"]]
        for r in (base, tail, rcz):
            q = r["points"][i]
            rs = q["response"] or {}
            tag = "" if q["classification"]["valid"] else " INVALID"
            pm = rs.get("pm_deg")
            flag = "" if pm is None or pm >= 45 else " F"
            row.append(f"{f(pm)}{flag} / {f(rs.get('worst_gm_db'))} / {f(rs.get('crossover_hz'), 0)} / {rs.get('status')}{tag}")
        out.append("| " + " | ".join(row) + " |")
    out.append("\n## Iq (uA, VIN current minus load current; includes every added element)\n")
    out.append("| leg | baseline | tail x2 | R_CZ x16 |")
    out.append("|---|---|---|---|")
    for i, p in enumerate(base["points"]):
        if p["rload_ohm"] >= 1e11 and p["esr_ohm"] != 0.010:
            continue
        out.append(f"| {p['label']} | " + " | ".join(f(r['points'][i]['iq_a'] * 1e6, 3) for r in (base, tail, rcz)) + " |")
    out.append("\n## Baseline mechanism (phase / gain features per leg; descriptive, see README caveats)\n")
    out.append("| leg | DC gain dB | fc Hz | phase@fc deg | slope corners (Hz, step dB/dec) | doublet candidates |")
    out.append("|---|---|---|---|---|---|")
    for p in base["points"]:
        cs = "; ".join(f"{c['f_hz']:.3g} {c['slope_step_db_dec']:+.0f}" for c in p["corners"])
        db = "; ".join(f"p{d['pole_like_hz']:.3g}/z{d['zero_like_hz']:.3g}" for d in p["doublet_candidates"]) or "none"
        out.append(f"| {p['label']} | {f(p['response']['dc_gain_db'])} | {f(p['response']['crossover_hz'], 0)} | "
                   f"{f(p['phase_dip']['phase_at_fc_deg'])} | {cs} | {db} |")
    out.append("\n## Node transfers from VREF at crossover (mag dB, phase change from 10 mHz, deg), baseline 0 mA / 10 mOhm\n")
    out.append("| leg | " + " | ".join(base["points"][0]["nodes"]) + " |")
    out.append("|---|" + "---|" * len(base["points"][0]["nodes"]))
    for i in (0, 1, 6):
        p = base["points"][i]
        out.append(f"| {p['label']} | " + " | ".join(f"{f(v['mag_db_at_fc'])} / {f(v['phase_change_to_fc_deg'])}" for v in p["nodes"].values()) + " |")
    bt, rt = load("base_lt_tt")["meas"], load("rcz16_lt_tt")["meas"]
    out.append("\n## Load transient 1<->50 mA, R_CZ x16 vs same-session baseline (bounds: peak <=0.15 V, recovery <=20 us)\n")
    out.append("| metric | baseline | R_CZ x16 | bound |")
    out.append("|---|---|---|---|")
    for m in bt:
        lim = ll._bound(m)
        if lim is not None:
            out.append(f"| {m} | {f(bt[m], 3)} | {f(rt.get(m), 3)} | {lim} |")
    reg = ll.transient_regressions(bt, rt)
    out.append("\nRegression summary (R_CZ x16 vs baseline): " +
               ", ".join(f"{k}={sum(1 for t in reg if t['kind'] == k)}" for k in
                         ("new_violation", "worse_violation", "improved_violation", "missing")))
    out.append("\nNew violations:\n")
    for t in reg:
        if t["kind"] == "new_violation":
            out.append(f"- {t['metric']}: {t['base']} -> {t['cand']}")
    # verdicts
    def rows(r):
        return [{"valid": q["classification"]["valid"], "pm_deg": (q["response"] or {}).get("pm_deg") or 0.0,
                 "worst_gm_db": (q["response"] or {}).get("worst_gm_db") or 0.0} for q in r["points"]]
    iq = lambda r: [q["iq_a"] * 1e6 for q in r["points"]]
    out.append("\n## Machine verdicts (lightload_extract.verdict)\n")
    out.append(f"- tail x2: {ll.verdict(rows(tail), None, iq(tail))} (transient not run: rejected on Iq/margins first)")
    out.append(f"- R_CZ x16: {ll.verdict(rows(rcz), reg, iq(rcz))}")
    (HERE / "tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
