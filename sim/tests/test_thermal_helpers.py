class TestAt(unittest.TestCase):
    T = [0.0, 1e-6, 2e-6, 4e-6]
    Y = [10, 11, 12, 14]

    def test_exact(self):
        self.assertEqual(rc.at(self.T, self.Y, 2), 12)

    def test_nearest_both_sides_no_interpolation(self):
        self.assertEqual(rc.at(self.T, self.Y, 1.2), 11)
        self.assertEqual(rc.at(self.T, self.Y, 1.8), 12)

    def test_tie_first_index(self):
        self.assertEqual(rc.at([0.0, 2e-6, 4e-6], [7, 8, 9], 1), 7)
        self.assertEqual(rc.at([0.0, 2e-6], [1, 2], 1), 1)

    def test_out_of_range_endpoints(self):
        self.assertEqual(rc.at(self.T, self.Y, -5), 10)
        self.assertEqual(rc.at(self.T, self.Y, 99), 14)


class TestTripped(unittest.TestCase):
    def test_threshold(self):
        for sup in (3.3, 1.8):
            self.assertTrue(rc.tripped(sup / 2 - 0.01, sup))
            self.assertFalse(rc.tripped(sup / 2, sup))
            self.assertFalse(rc.tripped(sup / 2 + 0.01, sup))


class TestBisect(unittest.TestCase):
    def test_want_lowest(self):
        lo, hi = rc.bisect(lambda x: x >= 37.0, 0.0, 100.0, 0.5, True)
        self.assertLessEqual(hi - lo, 0.5)
        self.assertLess(lo, 37.0)
        self.assertGreaterEqual(hi, 37.0)

    def test_want_highest(self):
        lo, hi = rc.bisect(lambda x: x <= 37.0, 0.0, 100.0, 0.5, False)
        self.assertLessEqual(hi - lo, 0.5)
        self.assertLessEqual(lo, 37.0)
        self.assertGreater(hi, 37.0)

    def test_exact_bracket_sequence(self):
        self.assertEqual(rc.bisect(lambda x: x >= 40, 0.0, 100.0, 25.0, True), (25.0, 50.0))
        self.assertEqual(rc.bisect(lambda x: x <= 40, 0.0, 100.0, 25.0, False), (25.0, 50.0))

    def test_no_evaluation_when_within_tol(self):
        self.assertEqual(rc.bisect(lambda x: x >= 5, 0.0, 10.0, 10.0, True), (0.0, 10.0))

    def test_invalid_brackets(self):
        with self.assertRaises(AssertionError):  # hi fails
            rc.bisect(lambda x: x >= 200, 0.0, 100.0, 1.0, True)
        with self.assertRaises(AssertionError):  # lo already satisfies
            rc.bisect(lambda x: x >= -1, 0.0, 100.0, 1.0, True)
        with self.assertRaises(AssertionError):  # lo fails
            rc.bisect(lambda x: x <= -1, 0.0, 100.0, 1.0, False)
        with self.assertRaises(AssertionError):  # hi already satisfies
            rc.bisect(lambda x: x <= 200, 0.0, 100.0, 1.0, False)


class TestColdEnableTemps(unittest.TestCase):
    """The shared cold-start / EN re-enable schedule (issue #715)."""

    def test_literal_schedule_from_the_541_fixture_brackets(self):
        # midpoints of the RESET/TRIP fixture in test_batch_thermal_staircase_541.py
        self.assertEqual(rc.cold_enable_temps(159.15625, 172.15625),
                         [151, 158, 161, 166, 170, 173, 180])

    def test_narrow_window_two_offsets_round_together(self):
        # reset 160.0 / trip 163.4: `reset_mid + 2` (162.0) and the window
        # middle (161.7) both round to 162 C, so the schedule drops to six points.
        self.assertEqual(rc.cold_enable_temps(160.0, 163.4), [152, 159, 161, 162, 164, 171])

    def test_recorded_temps_replay_from_committed_brackets(self):
        """Every committed cold/en temperature set reproduces from its own
        record's brackets through the shared schedule (append-only evidence:
        this can only cover more pairs as records accrue)."""
        n = 0
        paths = sorted((SIM / "thermal" / "hysteresis").glob("*/result*.json"))
        paths += sorted((SIM / "thermal-regen-cmp" / "records").glob("*/result*.json"))
        for path in paths:
            d = json.loads(path.read_text())
            cases = d["corners"].items() if "corners" in d else [("tt", d)]  # flat local records
            for name, c in cases:
                r, t = c.get("t_reset_falling_c", {}), c.get("t_trip_rising_c", {})
                cold = c.get("cold_start_by_temp", {})
                en = c.get("en_reenable_by_temp", c.get("en_reenable_from_tripped_by_temp", {}))
                # eligible = brackets plus a (non-skipped) dependent-point plan or a measurement
                # field (even an empty one): bracket-only records predate the dependent points
                # and are skipped, but an emptied map must still be accounted for.
                planned = "dependent_points" in c and "skipped" not in c["dependent_points"]
                has_dep = (planned or "cold_start_by_temp" in c or "en_reenable_by_temp" in c
                           or "en_reenable_from_tripped_by_temp" in c)
                if "bracket" not in r or "bracket" not in t or not has_dep:
                    continue
                n += 1
                want = set(rc.cold_enable_temps(sum(r["bracket"]) / 2, sum(t["bracket"]) / 2))
                dp = c.get("dependent_points", {})
                # temperatures this record itself says were not measured, per label
                not_run = {"cold": set(), "en": set()}
                for entry in list(dp.get("missing", [])) + list(dp.get("beyond_grid_top_not_run", [])):
                    lab, _, temp = entry.partition("@")
                    if lab in not_run:
                        not_run[lab].add(float(temp.rstrip("C")))
                # cold-start and EN are checked separately, empty maps included: one
                # measurement must not hide a gap in the other. Points above a ceiling that did run are kept (got
                # is only required to be a subset of the schedule, e.g. ff at 185 C).
                for lab, rec in (("cold", cold), ("en", en)):
                    got = {float(k) for k in rec}
                    where = f"{path.name} {name} {lab}"
                    self.assertLessEqual(got, want, where)
                    self.assertEqual(want - got, not_run[lab], where)
        self.assertGreaterEqual(n, 34)  # 34 verified pairs at issue #715 filing


class TestReadDat(unittest.TestCase):
    def _read(self, rows, names):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "x.dat"
            p.write_text(rows)
            return rc.read_dat(p, names)

    def test_eight_names(self):
        names = ["ts_cmp", "rc_a", "rc_b", "ea_out", "vout", "en", "ts_sns", "ts_ref"]
        r1 = " ".join(f"0 {i + 1}" for i in range(8))
        r2 = " ".join(f"1e-6 {i + 11}" for i in range(8))
        t, v = self._read(f"{r1}\n\n{r2}\n", names)
        self.assertEqual(t, [0.0, 1e-6])
        self.assertEqual(v, {n: [float(i + 1), float(i + 11)] for i, n in enumerate(names)})

    def test_seven_names(self):
        names = ["ts_cmp", "rc_a", "rc_b", "ea_stub", "en", "ts_sns", "ts_ref"]
        r1 = " ".join(f"0 {i + 1}" for i in range(7))
        r2 = " ".join(f"2e-6 {i + 21}" for i in range(7))
        t, v = self._read(f"{r1}\n{r2}\n", names)
        self.assertEqual(t, [0.0, 2e-6])
        self.assertEqual(v, {n: [float(i + 1), float(i + 21)] for i, n in enumerate(names)})


class TestRunnerWiring(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.hyst = load("run_hysteresis", SIM / "thermal" / "run_hysteresis.py")
        cls.demo = load("run_demo", SIM / "thermal-regen-cmp" / "run_demo.py")

    def test_no_local_copies(self):
        for m in (self.hyst, self.demo):
            for fn in ("read_dat", "at", "tripped", "bisect", "cold_enable_temps"):
                self.assertIs(getattr(m, fn), getattr(rc, fn))
            # issue #597: the Runner shell is shared too, and no local PROGRESS_RE
            self.assertTrue(issubclass(m.Runner, rc.ThermalRunner))
            self.assertFalse(hasattr(m, "PROGRESS_RE"))
        # issue #715: the batch planner shares the schedule too
        self.assertIs(bts.cold_enable_temps, rc.cold_enable_temps)

    def test_hysteresis_instants_single_source(self):
        names = ("T_COLD", "T_FORCED", "T_HOLD", "T_EN_LOW", "T_REEN")
        # instants live on each bench's Runner class (issue #597), not at module level
        self.assertEqual(tuple(getattr(self.hyst.Runner, n) for n in names),
                         tuple(getattr(bts, n) for n in names))
        # the regen-cmp demo is a DIFFERENT bench: its instants must NOT be pinned to these
        self.assertNotEqual(tuple(getattr(self.demo.Runner, n) for n in names),
                            tuple(getattr(bts, n) for n in names))

    def test_vector_schemas(self):
        self.assertEqual(self.hyst.KEYS, ["ts_cmp", "rc_a", "rc_b", "ea_out", "vout", "en", "ts_sns", "ts_ref"])
        self.assertEqual(self.demo.KEYS, ["ts_cmp", "rc_a", "rc_b", "ea_stub", "en", "ts_sns", "ts_ref"])

    def test_deck_text_golden(self):
        self.assertEqual(self.hyst.deck_text(BODY, FakePdk(), 27.5, 0.5e-6, "0", "/tmp/x.dat"), GOLDEN_HYST)
        self.assertEqual(self.demo.deck_text(BODY, FakePdk(), 27.5, -0.25, "0", "/tmp/x.dat"), GOLDEN_DEMO)


